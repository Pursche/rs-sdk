 const text=JSON.stringify({version:1,stream:'stream',ownerId:'owner',events:[{version:1,id:'stream:1',tick:1,at:1000,kind:'death',cause:'npc_attack',script:'test',amount:0,beforeHp:1,afterHp:0,source,target}]});
